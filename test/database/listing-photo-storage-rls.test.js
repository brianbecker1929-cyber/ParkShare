// Run only against the disposable PostgreSQL database supplied by
// TEST_DATABASE_URL (GitHub Actions). NEVER connect this test to Supabase-QA
// or production: the fixture resets public/auth schemas.
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { before, beforeEach, after, describe, test } from "node:test";
import pg from "pg";

const { Pool } = pg;
const url = process.env.TEST_DATABASE_URL;
const fixturePath = new URL("./booking-holds-fixture.sql", import.meta.url);
const migrationPath = new URL("../../supabase-migration-013-listing-photos-storage.sql", import.meta.url);
const HOST = "00000000-0000-4000-8000-000000000271";
const DRIVER = "00000000-0000-4000-8000-000000000272";
const OTHER_HOST = "00000000-0000-4000-8000-000000000273";

describe("BUG-005135 listing-photos Storage policy", { skip: !url, concurrency: 1 }, () => {
  let pool;

  before(async () => {
    pool = new Pool({ connectionString: url, connectionTimeoutMillis: 5000, max: 3 });
    await pool.query(await readFile(fixturePath, "utf8"));
    // Minimal stand-in Storage metadata, used ONLY for testing RLS policies.
    // Actual Supabase files must be uploaded/deleted through the Storage API.
    await pool.query(`
      drop schema if exists storage cascade;
      create schema storage;
      create table storage.buckets (
        id text primary key, name text not null, public boolean not null,
        file_size_limit bigint, allowed_mime_types text[]
      );
      create table storage.objects (
        id bigint generated by default as identity primary key,
        bucket_id text not null references storage.buckets(id),
        name text not null
      );
      create function storage.foldername(path text) returns text[]
      language sql immutable strict as $$
        select case when position('/' in path) > 0
          then array[split_part(path, '/', 1)]
          else array[]::text[] end
      $$;
      create or replace function auth.uid() returns uuid
      language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
      $$;
      alter table public.profiles add column role text not null default 'driver';
      alter table public.profiles enable row level security;
      create policy "Profiles visible" on public.profiles for select using (true);
      alter table storage.objects enable row level security;
      grant usage on schema storage, public, auth to authenticated, anon;
      grant select on public.profiles to authenticated, anon;
      grant select, insert, update, delete on storage.objects to authenticated, anon;
    `);
    await pool.query(await readFile(migrationPath, "utf8"));
  });

  beforeEach(async () => {
    await pool.query("truncate storage.objects restart identity");
    await pool.query("truncate public.bookings, public.listings, public.profiles, auth.users restart identity cascade");
    await pool.query("insert into auth.users(id) values ($1), ($2), ($3)", [HOST, DRIVER, OTHER_HOST]);
    await pool.query("insert into public.profiles(id,role) values ($1,'host'), ($2,'driver'), ($3,'host')", [HOST, DRIVER, OTHER_HOST]);
  });

  after(async () => { await pool?.end(); });

  async function asUser(userId, statement, params = [], role = "authenticated") {
    const client = await pool.connect();
    try {
      await client.query("begin");
      await client.query("set local role " + (role === "anon" ? "anon" : "authenticated"));
      await client.query("select set_config('request.jwt.claim.sub',$1,true)", [userId || ""]);
      const result = await client.query(statement, params);
      await client.query("commit");
      return result;
    } catch (error) {
      await client.query("rollback").catch(() => {});
      throw error;
    } finally {
      client.release();
    }
  }

  const objectPath = id => id + "/10000000-0000-4000-8000-000000000001.jpg";
  async function insertObject(id, path = objectPath(id)) {
    return asUser(id,
      "insert into storage.objects(bucket_id,name) values ('listing-photos',$1) returning name", [path]);
  }

  test("creates a public bucket with 10 MB size and exact allowlisted MIME types", async () => {
    const { rows } = await pool.query("select public,file_size_limit,allowed_mime_types from storage.buckets where id='listing-photos'");
    assert.equal(rows.length, 1);
    assert.equal(rows[0].public, true);
    assert.equal(Number(rows[0].file_size_limit), 10485760);
    assert.deepEqual(rows[0].allowed_mime_types, ["image/jpeg", "image/png", "image/webp"]);
  });

  test("Host uploads within own UUID folder", async () => {
    const r = await insertObject(HOST);
    assert.equal(r.rows[0].name, objectPath(HOST));
  });

  test("Drivers and anonymous users cannot upload listing images", async () => {
    await assert.rejects(insertObject(DRIVER), error => error.code === "42501");
    await assert.rejects(
      asUser("", "insert into storage.objects(bucket_id,name) values ('listing-photos',$1)", [objectPath(HOST)], "anon"),
      error => error.code === "42501"
    );
    assert.equal((await pool.query("select count(*)::integer as n from storage.objects")).rows[0].n, 0);
  });

  test("Host cannot upload in another Host's folder", async () => {
    await assert.rejects(insertObject(HOST, objectPath(OTHER_HOST)), error => error.code === "42501");
  });

  test("Host may inspect and remove only own objects", async () => {
    await insertObject(HOST);
    await insertObject(OTHER_HOST);
    const seen = await asUser(HOST, "select name from storage.objects order by name");
    assert.deepEqual(seen.rows.map(r => r.name), [objectPath(HOST)]);
    const strangers = await asUser(HOST,
      "delete from storage.objects where name=$1 returning name", [objectPath(OTHER_HOST)]);
    assert.equal(strangers.rowCount, 0);
    const own = await asUser(HOST,
      "delete from storage.objects where name=$1 returning name", [objectPath(HOST)]);
    assert.equal(own.rowCount, 1);
    assert.equal((await pool.query("select count(*)::integer as n from storage.objects")).rows[0].n, 1);
  });

  test("Host cannot overwrite existing Storage object through UPDATE", async () => {
    await insertObject(HOST);
    const r = await asUser(HOST,
      "update storage.objects set name=$1 where name=$2 returning name",
      [objectPath(HOST).replace(".jpg", ".png"), objectPath(HOST)]);
    assert.equal(r.rowCount, 0);
  });

  test("changing Host role to Driver removes all authenticated Storage write access", async () => {
    await insertObject(HOST);
    await pool.query("update public.profiles set role='driver' where id=$1", [HOST]);
    await assert.rejects(insertObject(HOST, objectPath(HOST).replace(".jpg", ".png")), error => error.code === "42501");
    const removed = await asUser(HOST, "delete from storage.objects where name=$1", [objectPath(HOST)]);
    assert.equal(removed.rowCount, 0);
  });
});
